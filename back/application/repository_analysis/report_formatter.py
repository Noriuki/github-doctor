"""Format health report as Markdown and badge data."""

from back.domain.models import RepositoryHealthReport


def report_to_markdown(report: RepositoryHealthReport) -> str:
    """Convert a health report to Markdown text."""
    doc = report.documentation
    tests = report.tests
    cicd = report.cicd
    deps = report.dependencies

    lines = [
        "# Repository Health Report",
        "",
        f"**Repository:** {report.repository}",
        "",
        "## Summary",
        "",
        f"- **Documentation:** {doc.score}/10",
        f"- **Tests:** {tests.message}",
        f"- **CI/CD:** {cicd.message}",
        f"- **Dependencies:** {deps.message}",
        "",
        f"## Health Score: {report.health_score:.0f}%",
        "",
        "---",
        "",
        "### Documentation",
        f"- README: {'Yes' if doc.has_readme else 'No'}",
        f"- Size: {doc.readme_size_bytes} bytes",
        f"- Badges: {'Yes' if doc.has_badges else 'No'}",
        f"- Installation section: {'Yes' if doc.has_installation else 'No'}",
        f"- Usage section: {'Yes' if doc.has_usage else 'No'}",
        "",
        "### Tests",
        f"- Status: {tests.present.value}",
        f"- Directories: {', '.join(tests.test_dirs) or 'None'}",
        f"- Test files (sample): {tests.test_files_count}",
        "",
        "### CI/CD",
        f"- Detected: {cicd.detected}",
        f"- Type: {cicd.type.value}",
        f"- Workflows: {', '.join(cicd.workflow_files) or 'None'}",
        "",
        "### Dependencies",
        f"- Files: {', '.join(deps.dependency_files) or 'None'}",
        f"- Total dependencies: {deps.total_dependencies}",
        f"- Outdated: {deps.outdated_count}",
        "",
        "*Generated by [GitHub Doctor](https://github.com/your-org/github-doctor)*",
    ]
    return "\n".join(lines)


def get_badge_color(score: float) -> str:
    """Return badge color based on score (shields.io style)."""
    if score >= 80:
        return "brightgreen"
    if score >= 60:
        return "green"
    if score >= 40:
        return "yellow"
    if score >= 20:
        return "orange"
    return "red"


def get_badge_url(report: RepositoryHealthReport, base_url: str = "https://img.shields.io") -> str:
    """Return shields.io badge URL for the health score."""
    score = report.health_score
    color = get_badge_color(score)
    # shields.io: label-value-color
    label = "repository%20health"
    value = f"{score:.0f}%25"
    return f"{base_url}/badge/{label}-{value}-{color}"
